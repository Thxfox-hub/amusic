keys = sorted(T.keys(), key=len, reverse=True)
replaced = 0
for f in ROOT.rglob("*.rs"):
    src = f.read_text(encoding="utf-8")
    orig = src
    for k in keys:
        lit = '"%s"' % k
        rep = '"%s"' % T[k]
        if lit in src:
            replaced += src.count(lit)
            src = src.replace(lit, rep)
    if src != orig:
        f.write_text(src, encoding="utf-8")

print("remplacements:", replaced)
# reliquats : littéraux contenant du cyrillique non couverts
left = []
for f in ROOT.rglob("*.rs"):
    for i, line in enumerate(f.read_text(encoding="utf-8").splitlines(), 1):
        if line.lstrip().startswith(("//", "///")):
            continue
        for m in re.finditer(r'"[^"]*[А-Яа-яЁё][^"]*"', line):
            left.append(f"{f.name}:{i}: {m.group(0)}")
print("reliquats (littéraux hors commentaires):")
print("\n".join(left[:40]) or "  aucun")
